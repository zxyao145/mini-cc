import { afterEach, expect, it, vi } from 'vitest';
import { ProgressWriter, PendingProgress } from './progress-writer';
const pos = { textOffset: 20, blockIndex: 2, blockRatio: .4, percent: 40 };
const saved = (version: string) => ({progressUpdatedAt:version,readingStatus:'reading' as const,lastReadAt:version});
afterEach(() => vi.useRealTimers());
it('serializes and coalesces writes, with reset last so late requests cannot restore position', async () => {
  let release!: (value: ReturnType<typeof saved>) => void;
  const send = vi.fn().mockImplementationOnce(() => new Promise(r => {release=r;})).mockResolvedValue(saved('v2'));
  const reset = vi.fn().mockResolvedValue(saved('v3'));
  const writer = new ProgressWriter('page', 'v0', {send,reset,persist:vi.fn(),onChange:vi.fn(),onSaved:vi.fn()});
  writer.queue(pos); const first = writer.flush();
  writer.queue({...pos,percent:50}); writer.queue({...pos,percent:60});
  const clearing = writer.reset();
  expect(send).toHaveBeenCalledTimes(1); expect(reset).not.toHaveBeenCalled();
  release(saved('v1')); await first; await clearing;
  expect(send).toHaveBeenCalledTimes(1); expect(reset).toHaveBeenCalledTimes(1);
  expect(writer.baseUpdatedAt).toBe('v3'); expect(writer.pending).toBeNull();
});
it('keeps the original pending base after reopening and pauses 409 until an explicit choice', async () => {
  vi.useFakeTimers();
  const pending: PendingProgress = {position:pos,baseUpdatedAt:'old'};
  const current = {...pos,percent:63,progressUpdatedAt:'new'};
  const send = vi.fn().mockRejectedValueOnce({status:409,current}).mockResolvedValue(saved('newer'));
  const persist = vi.fn();
  const writer = new ProgressWriter('new-page','new',{send,reset:vi.fn(),persist,onChange:vi.fn(),onSaved:vi.fn()},pending);
  await writer.flush();
  expect(send.mock.calls[0][0].baseUpdatedAt).toBe('old');
  expect(send.mock.calls[0][0].sessionId).toBe('new-page');
  expect(writer.conflict).toEqual(current);
  await vi.advanceTimersByTimeAsync(90000); await writer.flush();
  expect(send).toHaveBeenCalledTimes(1);
  writer.resolveConflict(current,false); await writer.flush();
  expect(send.mock.calls[1][0].baseUpdatedAt).toBe('new');
  expect(persist).toHaveBeenLastCalledWith(null);
});
it('persists a failed position, suspends retries while hidden, and only acknowledges a successful save', async () => {
  vi.useFakeTimers();
  const send = vi.fn().mockRejectedValueOnce({status:503}).mockResolvedValue(saved('v1'));
  const changes = vi.fn(), persist = vi.fn();
  const writer = new ProgressWriter('page','v0',{send,reset:vi.fn(),persist,onChange:changes,onSaved:vi.fn()});
  writer.queue(pos); await writer.flush();
  expect(changes).toHaveBeenLastCalledWith('unsynced',null);
  expect(persist).toHaveBeenLastCalledWith({position:pos,baseUpdatedAt:'v0'});
  writer.setVisible(false); await vi.advanceTimersByTimeAsync(30000); expect(send).toHaveBeenCalledTimes(1);
  writer.setVisible(true); await writer.flush(); expect(changes).toHaveBeenLastCalledWith('synced',null);
});
it('flushes latest queued position with keepalive after the current write, retaining storage until its own ack', async () => {
  let release!: (value: ReturnType<typeof saved>)=>void;
  let finish!: (value: ReturnType<typeof saved>)=>void;
  const send=vi.fn().mockImplementationOnce(()=>new Promise(r=>{release=r;})).mockImplementationOnce(()=>new Promise(r=>{finish=r;}));
  const persist=vi.fn(),changes=vi.fn();
  const writer=new ProgressWriter('page','v0',{send,reset:vi.fn(),persist,onChange:changes,onSaved:vi.fn()});
  writer.queue(pos);const first=writer.flush();writer.queue({...pos,percent:80});
  writer.setVisible(false);const leaving=writer.flush(true);
  expect(send).toHaveBeenCalledTimes(1);
  expect(persist).toHaveBeenLastCalledWith({position:{...pos,percent:80},baseUpdatedAt:'v0'});
  release(saved('v1'));await first;await Promise.resolve();
  expect(send).toHaveBeenCalledTimes(2);
  expect(send.mock.calls[1][0]).toMatchObject({percent:80,baseUpdatedAt:'v1'});
  expect(send.mock.calls[1][1]).toBe(true);
  expect(changes).not.toHaveBeenLastCalledWith('synced',null);
  finish(saved('v2'));await leaving;
  expect(persist).toHaveBeenLastCalledWith(null);
  expect(changes).toHaveBeenLastCalledWith('synced',null);
});
it('orders explicit state changes after earlier progress responses and pauses automatic writes until state acknowledgement', async()=>{
  let release!: (value: ReturnType<typeof saved>)=>void;
  const order:string[]=[];
  const send=vi.fn().mockImplementationOnce(()=>new Promise(r=>{release=r;})).mockResolvedValue({...saved('v2'),readingStatus:'read'});
  const writer=new ProgressWriter('page','v0',{send,reset:vi.fn(),persist:vi.fn(),onChange:vi.fn(),onSaved:result=>order.push(result.readingStatus)});
  writer.queue(pos);const first=writer.flush();
  const state=writer.withStateChange(async()=>{order.push('read');});
  writer.queue({...pos,percent:80});
  expect(order).toEqual([]);
  release(saved('v1'));await first;await state;
  expect(order).toEqual(['reading','read']);
  await writer.flush();expect(order).toEqual(['reading','read','read']);
});
it('flushes previously qualified queued progress before acknowledging unread, with no trailing old save',async()=>{
  vi.useFakeTimers();let status='read';const order:string[]=[];
  const send=vi.fn().mockImplementation(async()=>{if(status==='unread')status='reading';order.push(`PUT:${status}`);return {...saved('v1'),readingStatus:status};});
  const writer=new ProgressWriter('page','v0',{send,reset:vi.fn(),persist:vi.fn(),onChange:vi.fn(),onSaved:vi.fn()});
  writer.queue(pos);await writer.flush();writer.queue({...pos,percent:60});
  await writer.withStateChange(async()=>{status='unread';order.push('PATCH:unread');},true);
  await vi.advanceTimersByTimeAsync(10000);
  expect(order).toEqual(['PUT:read','PUT:read','PATCH:unread']);expect(status).toBe('unread');
});
it('does not acknowledge unread while a pre-action position remains failed or conflicted',async()=>{
  const action=vi.fn();const send=vi.fn().mockRejectedValue({status:503});
  const writer=new ProgressWriter('page','v0',{send,reset:vi.fn(),persist:vi.fn(),onChange:vi.fn(),onSaved:vi.fn()});
  writer.queue(pos);
  await expect(writer.withStateChange(action,true)).rejects.toThrow();
  expect(action).not.toHaveBeenCalled();expect(writer.pending?.position).toEqual(pos);writer.setVisible(false);
});
it('keeps retry backoff when an unread action is blocked by unsaved progress',async()=>{
  vi.useFakeTimers();const send=vi.fn().mockRejectedValue({status:503});
  const writer=new ProgressWriter('page','v0',{send,reset:vi.fn(),persist:vi.fn(),onChange:vi.fn(),onSaved:vi.fn()});
  writer.queue(pos);await expect(writer.withStateChange(vi.fn(),true)).rejects.toThrow();
  await vi.advanceTimersByTimeAsync(1000);expect(send).toHaveBeenCalledTimes(1);
  await vi.advanceTimersByTimeAsync(1000);expect(send).toHaveBeenCalledTimes(2);writer.setVisible(false);
});
